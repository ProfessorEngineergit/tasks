let lang = 'en';

export function detectLanguage() {
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  return nav.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function setLanguage(value) {
  lang = value === 'auto' || !dict[value] ? detectLanguage() : value;
  document.documentElement.lang = lang;
}

export function getLanguage() { return lang; }

export function t(key, vars) {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

// Pick from an inline {de, en} pair (used by the settings schema).
export function tl(pair) {
  if (typeof pair === 'string') return pair;
  return pair[lang] ?? pair.en;
}

// Fill [data-i18n] / [data-i18n-placeholder] / [data-i18n-label] in static markup.
export function translateDom(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-label]').forEach(el => {
    const v = t(el.dataset.i18nLabel);
    el.setAttribute('aria-label', v);
    el.title = v;
  });
}
